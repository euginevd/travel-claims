"""Aurora DSQL on AWS (decision 30): IAM sign-in, and the schema built from the models.

DSQL takes one schema change per transaction and builds indexes asynchronously, so the
migrations, written for PostgreSQL, don't run there. Its database starts empty, so the schema
is created from the tables in db.py and stamped as the newest migration instead.
"""

from typing import Any, cast
from urllib.parse import urlsplit

from sqlalchemy import Connection, Engine, event, inspect, text
from sqlalchemy.schema import CreateIndex, CreateTable

# Kept under DSQL's one-hour limit on a connection.
RECYCLE_SECONDS = 50 * 60
# A write that lost a race with another, which DSQL reports at commit instead of waiting.
CONFLICT = "40001"


def is_dsql(url: str) -> bool:
    """Whether the url names a DSQL cluster's endpoint."""
    host = urlsplit(url).hostname or ""
    return ".dsql." in host and host.endswith(".on.aws")


def region_of(host: str) -> str:
    """The region in an endpoint such as <id>.dsql.ap-southeast-2.on.aws."""
    return host.split(".dsql.", 1)[1].split(".", 1)[0]


def sign_in_with_iam(engine: Engine) -> None:
    """A fresh 15-minute admin token as the password of each new connection."""
    import boto3  # noqa: PLC0415  # pyright: ignore[reportMissingTypeStubs]

    @event.listens_for(engine, "do_connect")
    def _token(_dialect: object, _record: object, _args: object, params: dict[str, Any]) -> None:
        host = str(params["host"])
        client = cast(Any, boto3).client("dsql", region_name=region_of(host))
        params["password"] = client.generate_db_connect_admin_auth_token(host, region_of(host))


def is_conflict(error: BaseException) -> bool:
    """Whether a database error is a lost race, safe for the caller to try again."""
    return getattr(getattr(error, "orig", None), "sqlstate", None) == CONFLICT


def dsql_ddl(statement: str) -> str:
    """PostgreSQL DDL as DSQL takes it: identity columns for SERIAL, asynchronous indexes."""
    statement = statement.replace(
        "SERIAL NOT NULL", "BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 1)"
    )
    return statement.replace("INDEX IF NOT EXISTS", "INDEX ASYNC IF NOT EXISTS", 1)


def create_schema(db: Connection, head: str) -> bool:
    """Create every table and index, one statement at a time, then stamp head. Says whether it
    did; a database already stamped is left as it is. db must be in autocommit."""
    from undercover_api.db import metadata  # noqa: PLC0415

    if inspect(db).has_table("alembic_version"):
        return False
    dialect = db.dialect
    for table in metadata.sorted_tables:
        db.exec_driver_sql(
            dsql_ddl(str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)))
        )
        for index in table.indexes:
            ddl = dsql_ddl(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect)))
            built = db.exec_driver_sql(ddl)
            job = built.scalar() if built.returns_rows else None
            if (
                job is not None
                and not db.execute(text("SELECT sys.wait_for_job(:job)"), {"job": job}).scalar()
            ):
                raise RuntimeError(f"DSQL couldn't build index {index.name}")
    db.exec_driver_sql(
        "CREATE TABLE IF NOT EXISTS alembic_version (version_num VARCHAR(32) NOT NULL, "
        "CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num))"
    )
    db.execute(
        text("INSERT INTO alembic_version (version_num) VALUES (:head) ON CONFLICT DO NOTHING"),
        {"head": head},
    )
    return True
